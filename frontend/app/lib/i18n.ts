const messages: Record<Lang, Record<MessageKey, string>> = { en, ar };

export function toLang(value: string | undefined): Lang {
  return value === "ar" ? "ar" : "en";
}

export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  let text = messages[lang][key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replace(`{${name}}`, String(value));
    }
  }
  return text;
}

/** English lives at /…, Arabic at /ar/…. */
export function localePath(lang: Lang, path: string): string {
  const clean = path.startsWith("/") ? path : `/${path}`;
  if (lang === "en") return clean;
  return clean === "/" ? "/ar" : `/ar${clean}`;
}

/** The same page in the other language. */
export function switchLangPath(pathname: string, search: string): string {
  const isArabic = pathname === "/ar" || pathname.startsWith("/ar/");
  const next = isArabic ? pathname.slice(3) || "/" : pathname === "/" ? "/ar" : `/ar${pathname}`;
  return next + search;
}

/** Picks the field for the current language: pick(product, "name") → nameAr or nameEn. */
export function pick<T extends object>(lang: Lang, item: T, field: string): string {
  const record = item as Record<string, unknown>;
  const value = record[field + (lang === "ar" ? "Ar" : "En")];
  const fallback = record[field + "En"];
  return String(value || fallback || "");
}

/** Prices keep Latin digits in both languages, as in the approved Arabic screens. */
export function formatMoney(lang: Lang, amount: number): string {
  const number = new Intl.NumberFormat("en-EG", {
    minimumFractionDigits: Number.isInteger(amount) ? 0 : 2,
    maximumFractionDigits: 2,
  }).format(amount);
  return lang === "ar" ? `${number} ج.م` : `EGP ${number}`;
}

/** Text for a server code such as err.OUT_OF_STOCK or promo.MIN_ORDER; a generic message if unknown. */
export function translateCode(lang: Lang, prefix: "err" | "promo", code: string | undefined): string {
  const key = `${prefix}.${code}`;
  return key in en ? translate(lang, key as MessageKey) : translate(lang, "error.generic");
}

export function formatDateTime(lang: Lang, iso: string): string {
  return new Intl.DateTimeFormat(lang === "ar" ? "ar-EG-u-nu-latn" : "en-GB", {
    dateStyle: "medium",
    timeStyle: "short",
  }).format(new Date(iso));
}

export function useLang(): Lang {
  return toLang(useParams().lang);
}

export function useT() {
  const lang = useLang();
  return {
    lang,
    t: (key: MessageKey, vars?: Record<string, string | number>) => translate(lang, key, vars),
    href: (path: string) => localePath(lang, path),
    money: (amount: number) => formatMoney(lang, amount),
    code: (prefix: "err" | "promo", value: string | undefined) => translateCode(lang, prefix, value),
    dateTime: (iso: string) => formatDateTime(lang, iso),
    pick: <T extends object>(item: T, field: string) => pick(lang, item, field),
  };
}
